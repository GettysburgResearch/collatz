"""Complete enumeration of the valid sets R_K and the extremal survivors.

R_K = set of residues mod 64^K valid for K H-steps = the 2^K coded
residues, generated by the exact recursion (inverse branches):
    R_K = { (64 y + 17 e) * 81^{-1} mod 64^K : y in R_{K-1}, e in {0,1} }.

Outputs:
  * verification that |R_K| = 2^K and that members really run K steps;
  * the smallest nontrivial members (the extremal integer survivors --
    integers whose valid run exceeds their fair window the most);
  * survivor law: min nontrivial element vs the equidistribution
    prediction 64^K/2^K = 32^K;
  * archimedean equidistribution measurements for EQ (MINIMAL.md):
    counts in 64 equal buckets, and dyadic small-element counts;
  * chart-relevant survivors (A == 6,0,8,3 mod 17).
"""

import math
from collections import Counter

def Hrun(A, cap):
    r = 0
    while A % 64 in (0, 1) and r < cap:
        A = 81 * (A // 64) + A % 64
        r += 1
    return r


def main(KMAX=20):
    R = [0, 1]
    M = 64
    inv = pow(81, -1, 64 ** (KMAX + 1))
    print("K  |R_K|    min nontrivial      32^K (model)   ratio  "
          "bucket-chi2(63)")
    for K in range(2, KMAX + 1):
        M *= 64
        invK = inv % M
        R = sorted({(64 * y + 17 * e) * invK % M for y in R for e in (0, 1)})
        assert len(R) == 2 ** K, (K, len(R))
        # spot-verify membership
        for A in R[:3] + R[-3:]:
            assert Hrun(A, K) >= K
        nontriv = [A for A in R if A > 1]
        mn = min(nontriv)
        model = 32 ** K
        # equidistribution: 64-bucket counts
        b = Counter(A * 64 // M for A in R)
        exp = 2 ** K / 64
        chi = sum((b[i] - exp) ** 2 / exp for i in range(64))
        print(f"{K:2d} {2**K:8d}  {float(mn):.3e}  {float(model):.3e}"
              f"  {mn/model:7.3f}  {chi:8.1f}")
    # final-K detail
    K = KMAX
    print(f"\n== survivors at K = {K} (all integers < 64^{K} valid {K} steps) ==")
    nontriv = [A for A in R if A > 1]
    print("ten smallest nontrivial survivors:")
    for A in nontriv[:10]:
        run = Hrun(A, 200)
        print(f"  A = {A}  ({A.bit_length()} bits, fair window "
              f"{A.bit_length()/6:.1f} steps, actual run {run}"
              f"{'+' if run >= 200 else ''}, class {A % 17} mod 17)")
    # excess-run law: run/fair-window for the smallest survivors
    best = max(Hrun(A, 400) / (A.bit_length() / 6) for A in nontriv[:200])
    print(f"max run/fair-window among 200 smallest: {best:.3f}")
    # chart-relevant
    chart = [A for A in nontriv if A % 17 in (6, 0, 8, 3)]
    print(f"chart-class survivors (mod 17 in {{6,0,8,3}}): "
          f"{len(chart)}/{len(nontriv)} = {len(chart)/len(nontriv):.4f} "
          f"(expected 4/17 = {4/17:.4f})")
    print(f"smallest chart-class survivor: A = {min(chart)} "
          f"(class {min(chart) % 17})")
    # dyadic small-element counts vs equidistribution
    print("\nsmall-element counts (EQ test): #R_K below 64^{K*f}:")
    for f in (0.5, 0.7, 0.85, 0.95, 1.0):
        thr = 64 ** (K * f)
        cnt = sum(1 for A in R if A < thr)
        expc = 2 ** K * min(1.0, 64 ** (K * f) / 64 ** K)
        print(f"  f={f:4.2f}: {cnt:8d}  (equidistribution predicts "
              f"{expc:12.1f})")


if __name__ == '__main__':
    main()

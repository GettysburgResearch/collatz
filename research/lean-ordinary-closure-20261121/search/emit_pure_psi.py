#!/usr/bin/env python3
"""Export a frozen pure-psi search result to independently checked Lean rows.

The search program is not imported. Exact affine destinations and all operation
guards are reconstructed here; Lean's proved checker checks them again. This
program rejects an incomplete accounting of the 1440 source residue families,
but preserves the explicit unresolved families instead of treating them as rules.
"""

import argparse
import hashlib
import json
from pathlib import Path


def form(a, b):
    return f"⟨{a}, {b}⟩"


def path(start, moves, root):
    a, b = start
    out = []
    for move in moves:
        if move == "D":
            a, b = 2*a, 2*b
            ctor = ".double true"
        elif move == "E":
            if a % 2 or b % 2:
                raise ValueError("invalid even step")
            a, b = a//2, b//2
            ctor = ".double false"
        elif move == "O":
            if a % 2 or b % 2 != 1:
                raise ValueError("invalid odd step")
            a, b = 3*a//2, (3*b+1)//2
            ctor = ".odd true"
        elif move == "I":
            if 2*a % 3 or (2*b-1) % 3:
                raise ValueError("invalid inverse odd step")
            a, b = 2*a//3, (2*b-1)//3
            if a % 2 or b % 2 != 1:
                raise ValueError("inverse is not an odd affine source")
            ctor = ".odd false"
        elif move in ("+psi", "-psi"):
            if move == "+psi":
                query = a, b
                a, b = 2*a, 2*b-1
                ctor = ".query true .psi"
            else:
                if a % 2 or (b+1) % 2:
                    raise ValueError("invalid inverse psi query")
                a, b = a//2, (b+1)//2
                query = a, b
                ctor = ".query false .psi"
            if not (query[1] > 0 and query[0] <= root[0] and query[1] < root[1]):
                raise ValueError("psi query is not strictly below the source on every lift")
        else:
            raise ValueError(f"inactive or unknown operation {move!r}")
        if a < 0 or b <= 0:
            raise ValueError("nonpositive affine lift")
        out.append(f"{ctor} {form(a,b)}")
    return "["+", ".join(out)+"]", (a,b)


def emit(source, destination, receipt):
    raw = source.read_bytes()
    data = json.loads(raw)
    if data["initial_modulus"] != 1440 or data["weights"] != {"psi": 1}:
        raise ValueError("wrong modulus or active family")
    if data["types"]["psi"] != [1,0,2,-1]:
        raise ValueError("wrong affine psi definition")
    solved, unresolved = data["solved"], data["unresolved"]
    if (len(solved), len(unresolved)) != (1265,175):
        raise ValueError("unexpected checkpoint counts")
    residues = []
    rows = []
    for item in solved:
        modulus, residue = item["cell"]
        if modulus != 1440 or item["kind"] != "psi" or residue <= 1:
            raise ValueError("wrong successful source family")
        if residue > 1441:
            raise ValueError("unexpected shifted source family")
        root = modulus, residue
        left, el = path(root,item["left"],root)
        right, er = path((2*modulus,2*residue-1),item["right"],root)
        if el != er or list(el) != item["endpoint"]:
            raise ValueError("endpoint mismatch")
        residues.append(residue % 1440)
        rows.append(f"  ⟨.psi, {form(*root)}, ⟨{left}, {right}⟩⟩")
    missing = []
    for modulus,residue,kind in unresolved:
        if modulus != 1440 or kind != "psi" or not 1 < residue <= 1440:
            raise ValueError("wrong unresolved source family")
        missing.append(residue)
    if sorted(residues+missing) != list(range(1440)):
        raise ValueError("successful and unresolved cells do not partition the source residues")
    if any(r % 2 for r in missing):
        raise ValueError("expected this checkpoint's unresolved cells to be even")
    sorted_residues = sorted(residues)
    if residues != sorted_residues[1:]+[0] or missing != sorted(missing):
        raise ValueError("expected the frozen source-residue rotation and sorted frontier")

    chunks = [rows[i:i+16] for i in range(0,len(rows),16)]
    text = [
        "/- Generated by emit_pure_psi.py. Valid rows are not a complete proof.",
        f"Source SHA-256: {hashlib.sha256(raw).hexdigest()}",
        "1265 checked psi rows; 175 explicitly unresolved even residue families. -/",
        "import Collatz.AffineJointDescent",
        "namespace CollatzAffineJoint.PurePsiCheckpoint",
        "set_option maxRecDepth 20000",
        "set_option maxHeartbeats 20000000",
        "def weights : Weights := ⟨1,1,1⟩",
        "def kinds : List Kind := [.psi]",
        "/-- Structural fuel avoids proof reduction in the library's well-founded merge. -/",
        "def mergeResidues : Nat → List Nat → List Nat → List Nat",
        "  | 0,xs,ys => xs++ys",
        "  | _+1,[],ys => ys",
        "  | _+1,xs,[] => xs",
        "  | k+1,x::xs,y::ys => if x≤y then x::mergeResidues k xs (y::ys)",
        "      else y::mergeResidues k (x::xs) ys",
        "theorem mem_mergeResidues (fuel z : Nat) (xs ys : List Nat) :",
        "    z∈mergeResidues fuel xs ys ↔ z∈xs ∨ z∈ys := by",
        "  induction fuel generalizing xs ys with",
        "  | zero => simp [mergeResidues]",
        "  | succ k ih =>",
        "    cases xs with",
        "    | nil => simp [mergeResidues]",
        "    | cons x xs =>",
        "      cases ys with",
        "      | nil => simp [mergeResidues]",
        "      | cons y ys =>",
        "        by_cases h : x≤y <;> simp [mergeResidues,h,ih,or_assoc,or_left_comm]",
    ]
    for i, chunk in enumerate(chunks):
        text.extend([
            f"def rules_{i} : List Row := [",
            ",\n".join(chunk),
            "]",
            f"theorem rules_{i}_valid : rules_{i}.all (Row.check weights kinds)=true := by decide",
        ])
    names = [f"rules_{i}" for i in range(len(chunks))]
    text.extend([
        "def rules : List Row := " + " ++ ".join(names),
        "theorem rules_valid : rules.all (Row.check weights kinds)=true := by",
        "  simp only [rules,List.all_append," + ",".join(n+"_valid" for n in names) + "]",
        "  rfl",
        "#print axioms rules_valid",
        "theorem rules_count : rules.length=1265 := by decide",
        "def solvedResidues : List Nat := [" + ",".join(map(str,sorted_residues)) + "]",
        "def unresolvedResidues : List Nat := [" + ",".join(map(str,missing)) + "]",
        "theorem residue_data_matches : rules.map (fun r => r.root.b%1440)=solvedResidues.tail++[0] := by decide",
        "theorem unresolved_count : unresolvedResidues.length=175 := by decide",
        "theorem unresolved_even : unresolvedResidues.all (fun r => decide (r%2=0))=true := by decide",
        "theorem unresolved_nonempty : unresolvedResidues≠[] := by decide",
        "#print axioms residue_data_matches",
        "#print axioms unresolved_even",
        "theorem residue_accounting :",
        "    mergeResidues 1440 solvedResidues unresolvedResidues=List.range 1440 := by decide",
        "theorem residue_covered (r : Nat) (hr : r<1440) : r∈solvedResidues ∨ r∈unresolvedResidues := by",
        "  have h : r∈List.range 1440 := List.mem_range.mpr hr",
        "  rw [← residue_accounting] at h",
        "  exact (mem_mergeResidues 1440 r solvedResidues unresolvedResidues).mp h",
        "theorem checked_row_sound {r : Row} (hr : r∈rules) (t : Nat)",
        "    (ih : LowerHyp weights kinds r.kind r.root t) : Comparison r.kind (r.root.eval t) :=",
        "  table_row_sound rules_valid hr t ih",
        "#print axioms residue_accounting",
        "#print axioms residue_covered",
        "#print axioms checked_row_sound",
        "end CollatzAffineJoint.PurePsiCheckpoint",
        "",
    ])
    destination.parent.mkdir(parents=True,exist_ok=True)
    destination.write_text("\n".join(text))
    record = {
        "status": "EXACT EXPORT; LEAN COMPILATION REQUIRED; INCOMPLETE GLOBAL COVER",
        "source_file": source.name,
        "source_sha256": hashlib.sha256(raw).hexdigest(),
        "generated_sha256": hashlib.sha256(destination.read_bytes()).hexdigest(),
        "successful_rows": len(rows),
        "unresolved_rows": len(missing),
        "proof_chunk_size": 16,
        "active_kinds": ["psi"],
        "unresolved_mod4": {str(r):sum(x%4==r for x in missing) for r in range(4)},
    }
    receipt.write_text(json.dumps(record,indent=2)+"\n")
    print(json.dumps(record,indent=2))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source",type=Path)
    parser.add_argument("destination",type=Path)
    parser.add_argument("--receipt",type=Path,required=True)
    args = parser.parse_args()
    emit(args.source,args.destination,args.receipt)

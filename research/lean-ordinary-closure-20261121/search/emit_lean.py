#!/usr/bin/env python3
"""Emit literal Lean certificates from a fixed-weight search checkpoint.

The Python program is an untrusted translator. JointDescent.lean checks every
edge, parity, multiplier query and strict rank inequality in Lean's kernel.
Unresolved rows are omitted from rules and explicitly retained in unresolved.
"""
from pathlib import Path
import argparse
import json

KINDS = {3: '.triple', 5: '.five'}

def form(a, b):
    return f'⟨{a}, {b}⟩'

def path(start, moves):
    a, b = start
    out = []
    for op in moves:
        if op == 'D':
            a, b = 2*a, 2*b
            code = '.double true'
        elif op == 'E':
            a, b = a//2, b//2
            code = '.double false'
        elif op == 'O':
            a, b = 3*a//2, (3*b+1)//2
            code = '.odd true'
        elif op == 'I':
            a, b = 2*a//3, (2*b-1)//3
            code = '.odd false'
        elif op[0] in 'MV' and int(op[1:]) in KINDS:
            q = int(op[1:])
            if op[0] == 'M':
                a, b = q*a, q*b
                direction = 'true'
            else:
                a, b = a//q, b//q
                direction = 'false'
            code = f'.query {direction} {KINDS[q]}'
        else:
            raise ValueError(f'unknown move {op}')
        out.append(f'{code} {form(a,b)}')
    return '[' + ', '.join(out) + ']'

def emit(data):
    w3, w5 = data['weights']
    rows = data['rows']
    good = [r for r in rows if not r.get('unresolved', False)]
    unresolved = [r for r in rows if r.get('unresolved', False)]
    lines = [
        '/- Generated by search/emit_lean.py. Validity is not completeness. -/',
        'import Collatz.JointDescent',
        'namespace CollatzJoint.Checkpoint',
        'set_option maxRecDepth 20000',
        'set_option maxHeartbeats 20000000',
        f'def weights : Weights := ⟨{w3}, {w5}⟩',
    ]
    chunk_names = []
    for start in range(0,len(good),16):
        name=f'rules_{start//16}'
        chunk_names.append(name)
        lines.append(f'def {name} : List Row := [')
        chunk=good[start:start+16]
        for i,r in enumerate(chunk):
            m,b=r['cell'];p=r['multiplier']
            lines.append(f'  ⟨{KINDS[p]}, {form(m,b)}, ⟨{path((m,b),r["left"])}, {path((p*m,p*b),r["right"])}⟩⟩' + (',' if i+1<len(chunk) else ''))
        lines += [']',f'theorem {name}_valid : {name}.all (Row.check weights) = true := by decide']
    lines += ['def rules : List Row := ' + ' ++ '.join(chunk_names),
              'theorem rules_valid : rules.all (Row.check weights) = true := by',
              '  simp only [rules, List.all_append, ' + ', '.join(n+'_valid' for n in chunk_names) + ']',
              '  rfl',
              f'theorem rules_count : rules.length = {len(good)} := by decide',
              'def unresolved : List (Kind × Form) := [']
    for i,r in enumerate(unresolved):
        m,b=r['cell'];p=r['multiplier']
        lines.append(f'  ({KINDS[p]}, {form(m,b)})' + (',' if i+1<len(unresolved) else ''))
    lines += [']',f'theorem unresolved_count : unresolved.length = {len(unresolved)} := by decide',
              '/-- Every stored row is an all-parameter descent rule under its explicit lower hypotheses. -/',
              'theorem every_rule_sound (r : Row) (hr : r ∈ rules) (t : Nat)',
              '    (ih : LowerHyp weights r.kind r.root t) : Comparison r.kind (r.root.eval t) :=',
              '  table_row_sound rules_valid hr t ih',
              'end CollatzJoint.Checkpoint','']
    return '\n'.join(lines)

def main():
    ap=argparse.ArgumentParser()
    ap.add_argument('checkpoint', type=Path)
    ap.add_argument('output', type=Path)
    args=ap.parse_args()
    args.output.write_text(emit(json.loads(args.checkpoint.read_text())),encoding='utf-8')

if __name__ == '__main__':
    main()

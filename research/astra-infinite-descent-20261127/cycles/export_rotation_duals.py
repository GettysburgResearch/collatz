"""Serialize the exact named affine rows and multipliers to kernel-checkable Lean data.

Usage: python export_rotation_duals.py > RotationDuals.lean
Row coordinates equal 10000 times the respective rational row. Delta is the upper
endpoint minus the lower endpoint, retaining a single sparse copy of shared data.
"""
from pathlib import Path
import json
from check_five_rotations import rows as local_rows
from check_six_rotations import rows as chain_rows
from check_near_circuit import LOW,HIGH

HERE=Path(__file__).resolve().parent


def sparse(row):
    entries=[]
    for i,value in enumerate(row):
        scaled=10000*value
        if scaled.denominator!=1:
            raise ValueError('nonintegral scaled endpoint coefficient')
        if scaled:
            entries.append(f'({i}, {scaled.numerator})')
    return '['+', '.join(entries)+']'


def main():
    print('import CubeDual\n\n/-! Exact sparse matrices for the arbitrary-rotation mismatch certificates.\nGenerated by export_rotation_duals.py from the full named physical rows.\nThe final certificates use the Lean kernel. -/\nnamespace Collatz.InfiniteDescent.RotationDuals\nopen CubeDual\nset_option maxRecDepth 100000\nset_option maxHeartbeats 0\n')
    case_names=[]
    for source,family,margin in (('five',local_rows,128),('six',chain_rows,512)):
        weights=json.loads((HERE/f'{source}_rotation_duals.json').read_text())
        for key,ws in weights.items():
            s,w=map(int,key.split(','))
            a,b=family(s,w,LOW),family(s,w,HIGH)
            name=f'cuts{s}wrap{w}'
            case_names.append(name)
            dimension=len(next(iter(a.values())))-1
            print(f'def {name} : Certificate := ⟨{dimension}, {s}, {w}, {margin}, [')
            lines=[]
            for label,weight in ws.items():
                base=a[label]
                delta=[y-x for x,y in zip(base,b[label])]
                lines.append(f'  ⟨"{label}", {weight}, {sparse(base)}, {sparse(delta)}⟩')
            print(',\n'.join(lines)+']⟩')
            print(f'theorem {name}_pass : passes {name} = true := by decide +kernel\n')
    print('def allCases : List Certificate := ['+', '.join(case_names)+']')
    print('theorem allCases_pass (c : Certificate) (h : c ∈ allCases) : passes c = true := by')
    print('  simp only [allCases, List.mem_cons, List.not_mem_nil, or_false] at h')
    print('  rcases h with '+' | '.join('rfl' for _ in case_names))
    for name in case_names:
        print(f'  · exact {name}_pass')
    print('\nend Collatz.InfiniteDescent.RotationDuals')


if __name__=='__main__':
    main()

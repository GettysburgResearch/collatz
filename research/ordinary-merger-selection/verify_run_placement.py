#!/usr/bin/env python3
"""Exact finite replay of the component-run placement composition.

No external dependencies. The finite examples do not certify a universal
routing budget or the polynomial synchronization theorem.
"""

from collections import deque
import argparse
import json
from pathlib import Path


class Failure(RuntimeError):
    pass


def require(condition, message):
    if not condition:
        raise Failure(message)


def step(n):
    require(n > 0, "nonpositive physical state")
    return n // 2 if n % 2 == 0 else (3 * n + 1) // 2


# M, canonical residue, bits/common clock, common odd count, intercept.
# Generated by the pinned PR146 affine-pair constructor; checked below by
# independent coefficient induction, not just by sampling ordinary lifts.
TEMPLATES = (
    (2, 4, 3, 1, 2),
    (3, 4, 5, 2, 2),
    (4, 388, 11, 5, 47),
    (5, 4484, 18, 7, 38),
)


def verify_template(template):
    size, residue, bits, odds, intercept = template
    require(0 <= residue < 1 << bits, "noncanonical template")
    require(1 <= odds <= bits, "template odd-count domain")
    require(0 < intercept < 2 * 3**odds and intercept % 3, "endpoint domain")
    require(size <= 1 << bits, "template longer than binary modulus")
    for offset in range(size):
        coefficient = 1 << bits
        constant = residue + offset
        count = 0
        for _ in range(bits):
            require(coefficient % 2 == 0, "unfixed affine parity")
            if constant % 2:
                coefficient = 3 * coefficient // 2
                constant = (3 * constant + 1) // 2
                count += 1
            else:
                coefficient //= 2
                constant //= 2
        require(
            (coefficient, constant, count) == (3**odds, intercept, odds),
            "affine identity mismatch",
        )
    return size


def padded_target(target, intercept, budget):
    numerator = 3**budget * (intercept + 2)
    denominator = 2**budget
    threshold = (numerator + denominator - 1) // denominator
    first_exponent = (3 * threshold).bit_length()
    for exponent in range(first_exponent, first_exponent + 6):
        if ((1 << exponent) * target) % 9 in (4, 7):
            predecessor = ((1 << exponent) * target - 1) // 3
            require(predecessor >= threshold, "padding below threshold")
            require(predecessor < 128 * target * threshold, "padding upper bound")
            require(predecessor % 2 and predecessor % 3, "padding not an odd unit")
            return predecessor, exponent, threshold
    raise Failure("no legal padding exponent in a full period")


def find_route(source, residue, precision, budget, depth_limit=20):
    modulus = 3**precision
    queue = deque([(source, (), 0)])
    seen = {source}
    examined = 0
    while queue:
        current, word, total = queue.popleft()
        examined += 1
        if current % modulus == residue % modulus:
            return current, word, examined
        if len(word) == depth_limit:
            continue
        for exponent in range(1, 7):
            if total + exponent > budget:
                continue
            numerator = (1 << exponent) * current - 1
            if numerator % 3:
                continue
            child = numerator // 3
            if child <= 0 or child % 3 == 0 or child in seen:
                continue
            require(child % 2, "inverse child not odd")
            seen.add(child)
            queue.append((child, word + (exponent,), total + exponent))
    raise Failure("finite route search exhausted; no universal inference")


def replay_inverse(source, word):
    current = source
    for exponent in word:
        numerator = (1 << exponent) * current - 1
        require(numerator % 3 == 0, "nonintegral inverse step")
        child = numerator // 3
        require(child > 0 and child % 2 and child % 3, "inverse state domain")
        replay = child
        for _ in range(exponent):
            replay = step(replay)
        require(replay == current, "shortcut inverse replay")
        current = child
    return current


def verify_placement(template, target, budget):
    size, residue, bits, odds, intercept = template
    predecessor, padding, threshold = padded_target(target, intercept, budget)
    end, word, examined = find_route(predecessor, intercept, odds, budget)
    require(sum(word) <= budget, "routing budget exceeded")
    require(replay_inverse(predecessor, word) == end, "route endpoint mismatch")
    require(end > intercept, "nonpositive free lift")
    require((end - intercept) % 3**odds == 0, "terminal residue mismatch")
    lift = (end - intercept) // 3**odds
    first = residue + (1 << bits) * lift
    last = first + size - 1
    clock = bits + sum(word) + padding
    require(last < (1 << (bits + 12)) * target * 3**budget, "height bound")
    require(clock <= bits + 2 * budget + 2 * odds + 12, "clock bound")
    for start in range(first, last + 1):
        value = start
        for _ in range(clock):
            value = step(value)
        require(value == target, "common-clock target replay")
    return {
        "block_length": size,
        "target": target,
        "template_bits": bits,
        "template_odd_count": odds,
        "budget_used_for_padding": budget,
        "padding_exponent": padding,
        "route_exponents": list(word),
        "actual_route_total": sum(word),
        "route_nodes_examined": examined,
        "first_start": str(first),
        "last_start": str(last),
        "common_clock": clock,
        "padded_target": str(predecessor),
        "terminal_state": str(end),
        "padding_threshold": str(threshold),
    }


def rejected(action, label):
    try:
        action()
    except Failure:
        return label
    raise Failure("negative control not rejected: " + label)


def verify():
    affine_arms = sum(verify_template(t) for t in TEMPLATES)
    rows = [
        verify_placement(template, target, 120)
        for template in TEMPLATES
        for target in (1, 5, 7, 31)
    ]
    row = next(r for r in rows if r["route_exponents"])
    bad_word = row["route_exponents"].copy()
    bad_word[0] += 1
    bad_template = list(TEMPLATES[0])
    bad_template[-1] += 1
    mutations = [
        rejected(lambda: verify_template(tuple(bad_template)), "changed template intercept"),
        rejected(
            lambda: replay_inverse(int(row["padded_target"]), bad_word),
            "changed first inverse exponent",
        ),
        rejected(
            lambda: require(
                (int(row["terminal_state"]) - (2 if row["block_length"] <= 3 else
                 47 if row["block_length"] == 4 else 38) - 1)
                % 3**row["template_odd_count"] == 0,
                "changed terminal class",
            ),
            "changed terminal residue",
        ),
    ]
    return {
        "status": "PASS",
        "scope": "Finite exact composition replay, not an all-target routing proof.",
        "arithmetic": "integers only",
        "all_lift_affine_arms_verified": affine_arms,
        "ordinary_blocks_verified": len(rows),
        "ordinary_starts_replayed": sum(r["block_length"] for r in rows),
        "total_route_nodes_examined": sum(r["route_nodes_examined"] for r in rows),
        "negative_controls_rejected": mutations,
        "examples": rows,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    report = verify()
    rendered = json.dumps(report, indent=2, sort_keys=True)
    if args.output:
        args.output.write_text(rendered + chr(10))
    print(rendered)


if __name__ == "__main__":
    main()

"""Rebuild exact first-low interval certificates for the shortcut Collatz map."""

import argparse
from collections import Counter
import json
from pathlib import Path


# The last entry is an ordinary target missed one step before the optimum.
CASES = [(2, 7, 8), (3, 15, 1), (4, 23, 3365), (5, 24, 14507)]


def predecessors(target, clock):
    layer = {target}
    for _ in range(clock):
        parents = {2 * value for value in layer}
        parents.update((2 * value - 1) // 3 for value in layer if value % 3 == 2)
        layer = {value for value in parents if value > target}
    return layer


def stable_grade(start, clock):
    value, grade = start, 0
    grades = []
    for _ in range(clock):
        grades.append(grade)
        odd = value % 2
        grade += odd
        value = (3 * value + 1) // 2 if odd else value // 2
    # Every earlier profile must stay above its terminal profile on every lift.
    if any(2 ** (clock - j) < 3 ** (grade - q) for j, q in enumerate(grades)):
        return None
    return grade


def covering_tree(width, clock, target, precision, levels):
    layer = predecessors(target, clock)
    choices = []
    for start in sorted(layer):
        if all(start + offset in layer for offset in range(1, width)):
            grades = {stable_grade(start + offset, clock) for offset in range(width)}
            if len(grades) == 1 and None not in grades:
                choices.append((grades.pop(), start))
    if not choices:
        raise ValueError(f"No stable block at target {target} and clock {clock}")
    grade, start = min(choices)
    if grade <= precision:
        levels[precision] += 1
        return start
    if precision >= clock:
        raise ValueError(f"Could not cover target class {target} modulo {3 ** precision}")
    return [covering_tree(width, clock, target + digit * 3 ** precision, precision + 1, levels)
            for digit in range(3)]


def leaves(tree):
    return 1 if isinstance(tree, int) else sum(leaves(child) for child in tree)


def lean_expression(tree, clock):
    if isinstance(tree, int):
        return f"(.leaf {clock} {tree})"
    return "(.fork " + " ".join(lean_expression(child, clock) for child in tree) + ")"


def write_proof(lean, tree, width, clock, target, precision):
    name = f"w{width}_r{target}_k{precision}"
    if leaves(tree) <= 7:
        body = lean_expression(tree, clock)
        proof = "  decide +kernel"
    else:
        children = [write_proof(lean, child, width, clock, target + i * 3 ** precision,
                                precision + 1) for i, child in enumerate(tree)]
        body = ".fork " + " ".join(children)
        checks = [f"treeCheck {width} {clock} {c} {target + i * 3 ** precision} {precision + 1}"
                  for i, c in enumerate(children)]
        proof = ("  change (" + " && ".join(checks) + ")=true\n  rw [" +
                 ",".join(c + "_ok" for c in children) + "]\n  rfl")
    lean.extend([f"private def {name} : Tree := {body}", "",
                 f"private theorem {name}_ok : treeCheck {width} {clock} {name} "
                 f"{target} {precision}=true := by", proof, ""])
    return name


def build():
    lean = ["module", "", "public import PassageIntervals", "import all PassageIntervals",
            "import all TowerSectionTree", "", "public section",
            "namespace Collatz.Itinerary.PassageIntervals", "", "open TowerSectionTree",
            "set_option autoImplicit false", "set_option maxRecDepth 100000",
            "set_option maxHeartbeats 8000000", "", "/- Generated by passage_interval_replay.py. -/", ""]
    results = []
    for width, clock, missed in CASES:
        layer = predecessors(missed, clock - 1)
        if any(all(start + j in layer for j in range(width)) for start in layer):
            raise ValueError(f"The alleged lower witness {missed} contains a whole block")
        levels = Counter()
        roots = []
        for unit in (1, 2):
            tree = covering_tree(width, clock, unit, 1, levels)
            roots.append(write_proof(lean, tree, width, clock, unit, 1))
        left, right = roots
        lean.extend([f"theorem width{width}_iff (h : Nat) : AllTargets {width} h ↔ {clock}≤h := by",
                     f"  apply optimal (h:={clock - 1}) (b:={missed}) (by decide) (by decide)",
                     "  · decide +kernel", f"  · exact from_trees {left} {right} {left}_ok {right}_ok",
                     "", f"#print axioms width{width}_iff", ""])
        results.append({"width": width, "least_clock": clock, "missed_target": missed,
                        "prior_layer_size": len(layer), "ternary_leaves": sum(levels.values()),
                        "maximum_ternary_precision": max(levels)})
    lean.append("end Collatz.Itinerary.PassageIntervals")
    return "\n".join(lean) + "\n", results


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--emit-lean", type=Path, help="write the regenerated Lean proof")
    args = parser.parse_args()
    source, results = build()
    if args.emit_lean:
        args.emit_lean.write_bytes(source.encode("utf-8"))
    else:
        existing = Path(__file__).with_name("mathlib") / "PassageIntervalData.lean"
        if existing.read_text(encoding="utf-8") != source:
            raise SystemExit("Regenerated Lean certificate differs from the checked-in file")
    print(json.dumps(results, indent=2))

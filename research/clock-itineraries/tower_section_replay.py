"""Rebuild the ternary certificates and replay the sharp clock and height obstructions."""
import argparse
from pathlib import Path


def inverse_layers(b, stride, horizon):
    leaves = [(b, stride)]
    yield leaves
    for _ in range(horizon):
        even = [(2*y, 2*s) for y, s in leaves]
        odd = [((2*y-1)//3, 2*s//3) for y, s in leaves if y % 3 == 2 and s % 3 == 0]
        leaves = even + odd
        yield leaves


def choose_leaf(b, depth, rank, lo, hi, den, num):
    stride = 3**depth
    for h, leaves in enumerate(inverse_layers(b, stride, hi)):
        if h < lo:
            continue
        points = set(leaves)
        choices = [x for x, s in points if x > 0 and den*x <= num*b and den*s <= num*stride
                   and all((3**r*x, 3**r*s) in points for r in range(1, rank+1))]
        if choices:
            return h, min(choices)
    return None


def make_tree(b, depth, parameters, tally):
    leaf = choose_leaf(b, depth, *parameters)
    if leaf is not None:
        tally[depth] = tally.get(depth, 0) + 1
        return leaf
    if depth >= parameters[2]:
        raise ValueError(f"No uniform affine section at target {b} and depth {depth}")
    return tuple(make_tree(b+i*3**depth, depth+1, parameters, tally) for i in range(3))


def lean_tree(tree, indent=2):
    if len(tree) == 2:
        return f"(.leaf {tree[0]} {tree[1]})"
    spacer = "\n" + " "*(indent+2)
    return "(.fork" + spacer + spacer.join(lean_tree(t, indent+2) for t in tree) + ")"


CASES = [
    ("pairFixed", (1, 14, 14, 27, 16384)),
    ("pairFlexible", (1, 0, 14, 81, 16384)),
    ("tripleFixed", (2, 28, 28, 243, 268435456)),
]


def data_source():
    blocks = ["""module

public import TowerSectionTree
import all TowerSectionTree

public section
namespace Collatz.Itinerary.TowerSectionData

open TowerSectionTree
set_option autoImplicit false
set_option maxRecDepth 12288
set_option maxHeartbeats 4000000

-- Generated by tower_section_replay.py. Each leaf is replayed against the ordinary map.
private theorem from_units {R lo hi den num : Nat} {u v : Tree}
    (one : check R lo hi den num u 1 1=true)
    (two : check R lo hi den num v 2 1=true) (b : Nat) (unit : b%3≠0) :
    Section R lo hi den num b := by
  rcases (show b%3=1 ∨ b%3=2 by omega) with odd | even
  · have eq : 1+3^1*(b/3)=b := by omega
    simpa only [eq] using sound u 1 1 one (b/3)
  · have eq : 2+3^1*(b/3)=b := by omega
    simpa only [eq] using sound v 2 1 two (b/3)
"""]
    for name, params in CASES:
        tally = {}
        args = " ".join(map(str, params))
        for a in [1, 2]:
            tree = make_tree(a, 1, params, tally)
            # Split the proof at the first two digits to bound kernel reduction memory.
            roots = []
            for i, child in enumerate(tree):
                b = a + 3*i
                label = f"{name}_{b}"
                roots.append(label)
                blocks.append(f"private def {label} : Tree :=\n  {lean_tree(child)}\n")
                blocks.append(f"private theorem {label}_ok : check {args} {label} {b} 2=true := by\n  decide +kernel\n")
            whole = f"{name}Unit{a}"
            blocks.append(f"private def {whole} : Tree := .fork {' '.join(roots)}\n")
            checks = ", ".join(s+"_ok" for s in roots)
            blocks.append(f"private theorem {whole}_ok : check {args} {whole} {a} 1=true := by\n"
                          f"  change (check {args} {roots[0]} {a} 2 && check {args} {roots[1]} {a+3} 2 &&\n"
                          f"    check {args} {roots[2]} {a+6} 2)=true\n  rw [{checks}]\n  rfl\n")
        blocks.append(f"theorem {name} (b : Nat) (unit : b%3≠0) : Section {args} b :=\n"
                      f"  from_units {name}Unit1_ok {name}Unit2_ok b unit\n")
        print(f"{name}: {sum(tally.values())} ternary leaves, deepest digit {max(tally)}")
    blocks.append("end Collatz.Itinerary.TowerSectionData\n")
    return "\n".join(blocks)


def replay_obstructions():
    for h, b, rank in [(13, 439, 1), (27, 475963, 2)]:
        points = {x for x, _ in list(inverse_layers(b, 0, h))[-1]}
        assert not any(all(3**r*x in points for r in range(1, rank+1)) for x in points)
        print(f"Target {b} has {len(points)} predecessors at {h} steps and no complete tower")
    for b, flexible, floor in [(556, False, (337344, 2902376448)),
                               (1093, True, (221079, 967458816))]:
        for h, leaves in enumerate(inverse_layers(b, 3**14, 14)):
            if h != 14 and not flexible:
                continue
            if h == 14:
                assert floor in leaves and (3*floor[0], 3*floor[1]) in leaves
            for x, s in leaves:
                for y, d in leaves:
                    assert ((3*x < y and 3*s <= d) or (y < 3*x and d <= 3*s)
                            or (floor[0] <= x and floor[1] <= s))
        print(f"Sharp minimum {floor[0]}+{floor[1]}t at target {b}+3^14 t")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="regenerate TowerSectionData.lean")
    args = parser.parse_args()
    expected = data_source()
    path = Path(__file__).with_name("TowerSectionData.lean")
    if args.write:
        path.write_bytes(expected.encode("utf8"))
    if path.read_text(encoding="utf8") != expected:
        raise SystemExit("TowerSectionData.lean disagrees with the regenerated proof data")
    replay_obstructions()


if __name__ == "__main__":
    main()

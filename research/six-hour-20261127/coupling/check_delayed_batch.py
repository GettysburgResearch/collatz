def check(ok, message):
    if not ok:
        raise ValueError(message)


def twos(x):
    return (x & -x).bit_length() - 1


@lru_cache(maxsize=None)
def base_unit(a, h):
    mask = (1 << h) - 1
    u = 33215 & mask
    for i in range(min(a, h-3)):
        small = u & ((1 << (h-i-3)) - 1)
        u = (u + (small*small << (i+3))) & mask
    return u


def unit_mod(b, h):
    """Compute (3^(12*2^b)-1)/2^(b+4) modulo 2^h by binomial expansion."""
    a = min(b, max(1, isqrt(h)))
    u = base_unit(a, h)
    if a == b:
        return u
    n = 1 << (b-a)
    modulus = 1 << h
    mask = modulus - 1
    coefficient = 1  # binomial(n-1,i-1), always odd for 1 <= i <= n
    upower = 1
    result = 0
    for i in range(1, min(n, h//(a+3)+1)+1):
        v = twos(i)
        shift = (i-1)*(a+4) - v
        odd_inverse = pow(i >> v, -1, modulus)
        upower = upower*u & mask
        if shift < h:
            result += upower * coefficient * odd_inverse << shift
        if i < n:
            coefficient = coefficient * ((n-i) >> v) * odd_inverse & mask
    return result & mask


def single(x):
    return (3*x+1)//2 if x % 2 else x//2


@lru_cache(maxsize=None)
def block_table(width):
    rows = []
    for start in range(1 << width):
        x = start
        odds = 0
        for _ in range(width):
            odds += x % 2
            x = single(x)
        mul = 3**odds
        rows.append((x, odds, mul, (x << width)-mul*start))
    return rows


def physical(x, h):
    """Return the exact endpoint, grade and signed affine numerator from x=A-1."""
    start = x
    grade = 0
    carry = -1
    used = 0
    while used < h:
        width = min(12, h-used)
        high, low = divmod(x, 1 << width)
        endpoint, p, multiplier, positive_carry = block_table(width)[low]
        x = multiplier*high + endpoint
        carry = multiplier*carry + (positive_carry << used)
        grade += p
        used += width
    check(x << h == 3**grade*(start+1)+carry, 'full signed affine identity')
    return x, grade, carry



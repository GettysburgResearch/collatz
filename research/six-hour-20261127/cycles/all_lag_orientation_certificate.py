"""Exact finite checks for the two-orientation rank-gap code."""
from fractions import Fraction as F
from itertools import product
from math import gcd
import json


def need(v, reason):
    if not v:
        raise ArithmeticError(reason)


def orientation_statistics():
    schedules=words=lags=forced_changes=0
    for p in range(3,13):
        for s in range(1,p):
            if gcd(p,s)!=1 or not F(1,2)<F(s,p)<F(2,3):
                continue
            m=[1+int(r+s>=p) for r in range(p)]
            schedules+=1
            for z in product(range(2),repeat=p):
                e=[m[r]+z[r]-z[(r+s)%p] for r in range(p)]
                if min(e)<1:
                    continue
                words+=1
                for t in range(1,(p//2)+1):
                    c=[int(r+t>=p) for r in range(p)]
                    v=[z[(r+t)%p]-z[r] for r in range(p)]
                    w=[x-y for x,y in zip(v,c)]
                    w2=[z[(r+p-t)%p]-z[r]-int(r+p-t>=p) for r in range(p)]
                    need(all(w2[(r+t)%p]==-1-w[r] for r in range(p)),'reverse rank relation')
                    mism=sum(e[r]!=e[(r+t)%p] for r in range(p))
                    wc=sum(w[r]!=w[(r+s)%p] for r in range(p))
                    need(mism==wc,'change count')
                    jumps=sum(c[r]!=c[(r+s)%p] for r in range(p))
                    need(jumps==2*min(t,p-t,s,p-s),'cyclic interval boundary')
                    neq=sum(x!=0 for x in v)
                    need(jumps<=mism+2*neq,'unequal endpoints')
                    x=sum(a==1 and b==-1 for a,b in zip(c,w))
                    y=sum(a==0 and b==0 for a,b in zip(c,w))
                    need(x+y==p-neq,'ambiguities partition equal pairs')
                    for r in range(p):
                        a=(r+s)%p
                        forced_changes+=bool(w[r] not in (-1-c[a],-c[a],1-c[a]))
                        need(abs(w[r]-w[a])<=2,'jump between peripheral values')
                    lags+=1
    return dict(mechanical_schedules=schedules,legal_full_words=words,
                word_lag_cases=lags,forced_changes_observed=forced_changes)


def tilted_paths(c, num, den):
    # Exact scaled tilted count over all words with legal symbols (including
    # extra paths whose changes are not generated by actual ranks).
    d={w:1 for w in (-1-c[0],-c[0],1-c[0])}
    for h in c[1:]:
        d={w:sum(n*(den if v==w else num) for v,n in d.items() if abs(v-w)<=2)
           for w in (-1-h,-h,1-h)}
    return sum(d.values())


def charge_constants():
    # At t=1/47, 1+t+8t²=2264/2209.
    need(2264**216*47**6*2**73 <2209**216*3**72,'balanced sector exponent')
    need(36**36*2**10<35**35*3**12,'small orientation exponent')
    lo,hi=F(584961,10**6),F(584964,10**6)
    need(max(2*hi-1,2-3*lo)<F(246,1000),'five-point net')
    near=max(abs(53*x-31)*53 for x in (lo,hi))
    need(near<F(1,5),'53-grid approximation')
    classic_margin=F(109,100)/F(128,25) - F(7,10)*(F(1,4)+F(7,530)+F(26,1000))-F(9,1000)
    need(classic_margin>0,'classical exponent')
    # The finite enumeration here only supports the elementary weighted run count.
    samples=0
    for n in range(2,13):
        for c in product((0,1),repeat=n):
            if any(len(set(c[i:i+5]))==1 for i in range(n-4)):
                continue
            val=F(tilted_paths(c,1,47),47**(n-1))
            need(val<=50*F(2264,2209)**n,'tilted path test')
            samples+=1
    return dict(classical_rational_slack=str(classic_margin),worst_grid_constant=str(near),
                five_point_max_gap_upper=str(max(2*hi-1,2-3*lo)),tilted_run_schedules=samples)


if __name__=='__main__':
    print(json.dumps(dict(orientations=orientation_statistics(),constants=charge_constants()),
                     indent=2,sort_keys=True))

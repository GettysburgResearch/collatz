#!/usr/bin/env python3
"""Generate or check the small ordinary-prefix Lean certificate.

The generated finite assertions are reduced by Lean's kernel. Python supplies
only concrete candidate clocks, so a faulty generator cannot certify a false
bound. Separate assertions keep kernel reduction memory bounded.
"""
from __future__ import annotations

import argparse
from pathlib import Path


def render() -> str:
    clocks = [0]
    for n in range(1, 649):
        x, t, odds, seen, maximum = n, 0, 0, set(), 0
        while x != 1:
            if x in seen or t >= 10000:
                raise ArithmeticError(f"finite clock not found at source {n}")
            seen.add(x)
            odd = x & 1
            x = (3*x+1)//2 if odd else x//2
            odds += odd
            t += 1
            maximum = max(maximum, 2*odds-t)
        maximum = max(maximum, 2*odds-t+1)
        if maximum > 22:
            raise ArithmeticError(f"prefix bound exceeded at source {n}")
        clocks.append(t)
    pieces = ["""import AnchorBudget
import Mathlib.Tactic.IntervalCases

/-! Generated by make_anchor_certificate.py. Every finite candidate is
reduced by the kernel; all_prefixes_648 includes every future clock. -/
set_option autoImplicit false
set_option warningAsError true
set_option maxRecDepth 100000
set_option maxHeartbeats 40000000
namespace AnchorCertificate
open RampShadow AnchorBudget

"""]
    for n in range(1, 649):
        pieces.append(f"theorem source_{n} : budgetCheck {clocks[n]} {n} 22=true := by decide +kernel\n")
    pieces.append("""
theorem all_prefixes_648 {q : ℤ} (hp : 0<q) (hq : q≤648)
    (d p : ℕ) (z : ℤ) (w : Walk d p q z) : (2:ℤ)*p≤d+22 := by
  interval_cases q
""")
    for n in range(1, 649):
        pieces.append(f"  · exact budgetCheck_sound {clocks[n]} {n} 22 source_{n} w\n")
    pieces.append("\n#print axioms all_prefixes_648\nend AnchorCertificate\n")
    return "".join(pieces)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--path", type=Path, default=Path(__file__).with_name("AnchorCertificate.lean"))
    args = parser.parse_args()
    text = render()
    if args.check:
        if args.path.read_text() != text:
            raise SystemExit("generated certificate source differs")
    else:
        args.path.write_text(text)
    print("648 ordinary source clocks verified; certificate source matches" if args.check
          else "Generated 648 kernel-reducible source certificates")


if __name__ == "__main__":
    main()

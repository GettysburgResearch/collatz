#!/usr/bin/env python3
"""
Blueprint 1 Verifier: Exact (w^2 <-> w^3) Mahler Functional Equation,
Boolean Parseval Identity, and Rational/Periodic Exclusion.

Verifies:
1. Exact (w^2 <-> w^3) Mahler functional equation on f === 1 (F(z) = z/(1-z)) to 1e-13.
2. Exact Boolean Parseval identity: (1/2pi) int |F(r e^{i theta})|^2 dtheta == F(r^2) via FFT.
3. Exact finite-modulus non-existence of non-constant T-invariant periodic functions mod P
   for all odd P in [3, 99] (confirming Theorem 1.2's finite-period collapse).
4. Negative control: confirms a non-T-invariant {0,1} sequence (e.g. primes) violates the
   Mahler functional equation by O(1).
"""

import cmath
import json
import math
import numpy as np


def F_const_one(z: complex) -> complex:
    return z / (1.0 - z)


def F_series(coeffs: np.ndarray, z: complex) -> complex:
    # coeffs[n] = f(n) for n = 0..N-1 (with coeffs[0] = 0)
    powers = z ** np.arange(len(coeffs))
    return complex(np.dot(coeffs, powers))


def mahler_residual(F_fn, w: complex) -> float:
    omega = cmath.exp(2j * math.pi / 3.0)
    lhs = (F_fn(w**2) + omega * F_fn(omega * (w**2)) + (omega**2) * F_fn((omega**2) * (w**2))) / 3.0
    rhs = w * (F_fn(w**3) - F_fn(w**6))
    return abs(lhs - rhs)


def verify_periodic_exclusion(max_odd_p: int = 99):
    """
    For any odd period P >= 3, check that the equivalence relation on Z / P Z
    generated by x ~ 2x and (for odd lifts) x ~ (3x+1)/2 collapses to a single class
    whenever gcd(P, 3) == 1, and check exact component structure when 3 | P.
    Wait: for positive integers, f(2n) = f(n) and f(3n+1) = f(n) for odd n means
    on Z / P Z (P odd), 2x ~ x for all x, and for every x, there exists an odd integer
    n === x (mod P), so 3x + 1 ~ x for ALL x mod P!
    Let's verify that {x -> 2x, x -> 3x + 1} is ALWAYS transitive on Z / P Z for every odd P!
    """
    for P in range(3, max_odd_p + 1, 2):
        parent = list(range(P))

        def find(a):
            while parent[a] != a:
                parent[a] = parent[parent[a]]
                a = parent[a]
            return a

        def union(a, b):
            ra, rb = find(a), find(b)
            if ra != rb:
                parent[ra] = rb

        for x in range(P):
            union(x, (2 * x) % P)
            union(x, (3 * x + 1) % P)
        roots = {find(x) for x in range(P)}
        assert len(roots) == 1, f"Non-transitive mod P={P}: {len(roots)} components!"
    return True


def main():
    # 1. Exact Mahler functional equation on f === 1 across complex points in D
    test_ws = [0.3 + 0.2j, -0.4 + 0.5j, 0.65 - 0.1j, 0.1 + 0.7j]
    max_res_one = max(mahler_residual(F_const_one, w) for w in test_ws)
    assert max_res_one < 1e-13, f"Mahler residual too large: {max_res_one}"

    # 2. Exact Boolean Parseval identity on a {0,1} sequence (e.g. f(n) = 1 for all n >= 1, and also odd-square-free)
    N = 1024
    r = 0.6
    # Use a {0,1} indicator (e.g. indicators of n with v_2(n) even, just to test Parseval on nontrivial {0,1})
    coeffs = np.zeros(N, dtype=np.float64)
    for n in range(1, N):
        v = 0
        m = n
        while m % 2 == 0:
            m //= 2
            v += 1
        coeffs[n] = 1.0 if (v % 2 == 0) else 0.0

    # Evaluate on M = 2048 roots of unity on |z| = r via FFT
    M = 2048
    scaled = np.zeros(M, dtype=np.complex128)
    scaled[:N] = coeffs * (r ** np.arange(N))
    vals = np.fft.fft(scaled)
    l2_avg = float(np.mean(np.abs(vals) ** 2))
    f_r2 = float(np.dot(coeffs, (r ** 2) ** np.arange(N)))
    parseval_err = abs(l2_avg - f_r2)
    assert parseval_err < 1e-12, f"Parseval error too large: {parseval_err}"

    # 3. Verify periodic exclusion for all odd P in [3, 99]
    periodic_ok = verify_periodic_exclusion(99)

    # 4. Negative control: primes indicator violates the (w^2 <-> w^3) Mahler equation
    prime_coeffs = np.zeros(300, dtype=np.float64)
    for n in range(2, 300):
        if all(n % d != 0 for d in range(2, int(n**0.5) + 1)):
            prime_coeffs[n] = 1.0
    neg_res = mahler_residual(lambda z: F_series(prime_coeffs, z), 0.5 + 0.1j)
    assert neg_res > 1e-2, f"Negative control failed: prime residual was {neg_res}"

    result = {
        "blueprint": "blueprint_1_mahler_generating_function",
        "status": "PASS",
        "mahler_max_residual_f_eq_1": max_res_one,
        "boolean_parseval_error": parseval_err,
        "odd_period_transitivity_verified_up_to": 99,
        "periodic_exclusion_verified": periodic_ok,
        "negative_control_prime_residual": round(neg_res, 6),
    }
    print(json.dumps(result, indent=2))
    return result


if __name__ == "__main__":
    main()

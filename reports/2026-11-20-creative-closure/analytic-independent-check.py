#!/usr/bin/env python3
"""Independent leaf-current audit of the finite signed Hardy flows.

No production module is imported. Selected children are generated by the
recurrence q -> 4q+1. Each leaf is followed by literal shortcut iteration
to the root; its current is then transported forward along that path.
All arithmetic is scalar rational arithmetic, for lambda=1 and 21/20.
This finite audit does not replace the manuscript's infinite proofs.
"""
from __future__ import annotations

import argparse
from collections import defaultdict
from fractions import Fraction
from hashlib import sha256
import json
from pathlib import Path


REPO = Path(__file__).resolve().parents[2]
PINNED = {
    "research/creative-closure-20261120/analytic_flow.md":
        "6261ef1916469bc8357ee00ef07e7b55c37f668275c14af545cb8e2aa6d64bc6",
    "experiments/creative_analytic_flow.py":
        "d989cf46752581db238a629cf2ac3f16c2bd8c09d96dae095df330f401fe0e9a",
    "reports/2026-11-20-creative-closure/analytic-flow-report.json":
        "8cefbc6c0aa687dfb9ffa54f4b4f284d8c4423af62fc1acb44e21c9f4b4245a2",
}
COUNTS = defaultdict(int)


def require(condition, message):
    if not condition:
        raise ValueError(message)


def step(n):
    require(n > 0, "positive ordinary state required")
    return (3 * n + 1) // 2 if n % 2 else n // 2


def selected_children(parent):
    require(parent > 1 and parent % 2 and parent % 3, "invalid parent")
    first = (4 * parent - 1) // 3 if parent % 3 == 1 else (8 * parent - 1) // 3
    candidates = [first]
    for _ in range(2):
        candidates.append(4 * candidates[-1] + 1)
    selected = []
    for child in candidates:
        require(child > parent and child % 2, "invalid inverse candidate")
        cursor = step(child)
        clock = 1
        while cursor % 2 == 0:
            cursor = step(cursor)
            clock += 1
            require(clock <= 7, "macro clock exceeds seven")
        require(cursor == parent, "literal odd endpoint differs from parent")
        require(2 <= clock <= 7, "macro clock outside proved interval")
        COUNTS["candidate_shortcut_edges"] += clock
        COUNTS["candidate_macro_paths"] += 1
        if child % 3:
            selected.append(child)
    require(len(selected) == 2, "expected exactly two ternary units")
    return selected


def digest_vector(vector):
    # Deliberately use the public report's serialization only for comparison.
    payload = [[n, str(a), "0"] for n, a in sorted(vector.items())]
    return sha256(json.dumps(payload, separators=(",", ":")).encode()).hexdigest()


def energy(vector):
    return sum((a * a for a in vector.values()), Fraction())


def full_residual(vector, leaves, eigenvalue):
    incoming = defaultdict(Fraction)
    for n, amount in vector.items():
        incoming[step(n)] += amount
    keys = set(incoming) | set(vector)
    residual = {
        n: incoming[n] - eigenvalue * vector.get(n, 0)
        for n in keys
        if incoming[n] != eigenvalue * vector.get(n, 0)
    }
    expected = {n: -eigenvalue * vector[n] for n in leaves}
    require(residual == expected, "complete residual is not exactly the leaf defect")
    COUNTS["residual_coordinates_checked"] += len(keys)
    return residual


def build_from_leaves(root, depth, eigenvalue):
    require(depth > 0 and eigenvalue > 0, "positive depth and scalar required")
    frontier = [(root, 0)]
    levels = {root: 0}
    for generation in range(1, depth + 1):
        following = []
        for parent, sign in frontier:
            for branch, child in enumerate(selected_children(parent)):
                require(child not in levels, "inverse tree repeats a vertex")
                levels[child] = generation
                following.append((child, (1 if branch == 0 else -1) if generation == 1 else sign))
        frontier = following
    require(len(frontier) == 2 ** depth, "incomplete final generation")

    # Source currents are assigned only at leaves. Their ordinary paths are
    # obtained without reading parent pointers or closed-form even nodes.
    total = defaultdict(Fraction)
    received_at_root = Fraction()
    for leaf, sign in frontier:
        path = []
        cursor = leaf
        while cursor != root:
            require(len(path) < 7 * depth, "leaf did not reach root within clock")
            path.append(cursor)
            cursor = step(cursor)
        odd_path = [n for n in path if n % 2]
        require(len(odd_path) == depth, "wrong number of literal odd events")
        require([levels[n] for n in odd_path] == list(range(depth, 0, -1)),
                "literal forward path disagrees with inverse generations")
        amount = Fraction(sign, 2 ** (depth - 1)) * eigenvalue ** len(path)
        for n in path:
            total[n] += amount
            amount /= eigenvalue
        received_at_root += amount
        COUNTS["leaf_to_root_shortcut_edges"] += len(path)
        COUNTS["leaf_to_root_paths"] += 1
    require(received_at_root == 0, "root current did not cancel")
    vector = {n: a for n, a in total.items() if a}
    leaves = {leaf for leaf, _ in frontier}
    require(root not in vector, "root weight should be zero")
    residual = full_residual(vector, leaves, eigenvalue)
    squares = [sum((vector[n] ** 2 for n, d in levels.items() if d == j), Fraction())
               for j in range(1, depth + 1)]
    ratio = max(eigenvalue ** 4, eigenvalue ** 14) / 2
    require(ratio < 1, "outside sufficient eigenvalue disk")
    require(squares[0] <= 4 * ratio, "initial generation violates square bound")
    for previous, following in zip(squares, squares[1:]):
        require(following <= ratio * previous, "generation square bound violated")
    internal = sum((eigenvalue ** (2 * k) for k in range(1, 7)), Fraction())
    tail = squares[-1] * (internal + ratio) / (1 - ratio)
    if eigenvalue == 1:
        require(squares == [Fraction(4, 2 ** j) for j in range(1, depth + 1)],
                "stationary generation energy differs")
        require(energy(residual) == Fraction(4, 2 ** depth), "stationary residual energy differs")
        require(sum(abs(a) for a in residual.values()) == 2, "stationary residual mass differs")
        require(energy(vector) <= 32, "stationary full energy exceeds bound")
    return vector, leaves, {
        "root": root,
        "depth": depth,
        "eigenvalue": str(eigenvalue),
        "leaf_count": len(leaves),
        "nonzero_physical_coordinates": len(vector),
        "norm_squared": str(energy(vector)),
        "residual_norm_squared": str(energy(residual)),
        "generation_square_bound_ratio": str(ratio),
        "certified_omitted_square_tail_upper": str(tail),
        "vector_sha256": digest_vector(vector),
    }


def check_report_row(row, published):
    for key in ("leaf_count", "nonzero_physical_coordinates", "norm_squared",
                "residual_norm_squared", "generation_square_bound_ratio",
                "certified_omitted_square_tail_upper", "vector_sha256"):
        require(row[key] == published[key], "published scalar row differs: " + key)
    COUNTS["published_vector_hash_matches"] += 1


def triangular_check(height):
    # Compute the residual by coefficient lookup at T(n), as opposed to
    # assembling P from inverse images. At these inputs there are no odd
    # residual coordinates, since every supported exponent is divisible by 3.
    values = list(range(1, height + 1)) + list(range(height - 1, 0, -1))
    vector = {3 * 2 ** j: Fraction(a) for j, a in enumerate(values)}
    coordinates = set(vector) | {2 * n for n in vector}
    residual = {n: vector.get(n, 0) - vector.get(step(n), 0) for n in coordinates}
    require(energy(vector) == Fraction(2 * height ** 3 + height, 3), "triangle norm")
    require(energy(residual) == 2 * height, "triangle defect")
    require(energy(residual) / energy(vector) == Fraction(6, 2 * height * height + 1),
            "triangle ratio")
    COUNTS["triangular_cases"] += 1


def run():
    COUNTS.clear()
    for path, expected in PINNED.items():
        require(sha256((REPO / path).read_bytes()).hexdigest() == expected,
                "reviewed source bytes changed: " + path)
    published = json.loads((REPO / "reports/2026-11-20-creative-closure/analytic-flow-report.json").read_text())
    rows = {(r["root"], r["depth"], r["eigenvalue"][0]): r
            for r in published["flow_cases"] + published["antichain_cases"]
            if r["eigenvalue"][1] == "0"}
    records = []
    finite_tail_checks = []
    for eigenvalue in (Fraction(1), Fraction(21, 20)):
        built = []
        for depth in range(1, 9):
            vector, leaves, row = build_from_leaves(5, depth, eigenvalue)
            key = (5, depth, str(eigenvalue))
            if key in rows:
                check_report_row(row, rows[key])
            built.append((vector, row))
            records.append(row)
        deepest = built[-1][0]
        for vector, row in built[:-1]:
            require(all(deepest.get(n) == a for n, a in vector.items()),
                    "old physical coefficients failed to stabilize")
            new = {n: a for n, a in deepest.items() if n not in vector}
            require(energy(new) <= Fraction(row["certified_omitted_square_tail_upper"]),
                    "finite continuation exceeds infinite tail certificate")
            finite_tail_checks.append({
                "eigenvalue": str(eigenvalue), "from_depth": row["depth"],
                "to_depth": 8, "actual_added_square_energy": str(energy(new)),
                "infinite_tail_bound": row["certified_omitted_square_tail_upper"],
            })

    antichain = []
    stem = 5
    occupied = set()
    for _ in range(8):
        lower, upper = selected_children(stem)
        antichain.append(upper)
        vector, leaves, row = build_from_leaves(upper, 5, Fraction(1))
        require(occupied.isdisjoint(vector), "physical antichain supports intersect")
        occupied.update(vector)
        check_report_row(row, rows[(upper, 5, "1")])
        records.append(row)
        stem = lower
    require(antichain == published["antichain_roots"], "antichain differs")
    COUNTS["antichain_disjoint_pairs"] = 28
    COUNTS["finite_continuation_tail_checks"] = len(finite_tail_checks)

    for height in (1, 2, 3, 7, 13, 31):
        triangular_check(height)

    rejected = []
    vector, leaves, _ = build_from_leaves(5, 3, Fraction(1))
    for name in ("root_leakage", "unlisted_exterior_source"):
        changed = dict(vector)
        changed[5 if name == "root_leakage" else 3] = Fraction(1)
        try:
            full_residual(changed, leaves, Fraction(1))
        except ValueError:
            rejected.append(name)
        else:
            raise ValueError("negative control accepted: " + name)
    return {
        "schema": "collatz-creative-analytic-independent/v1",
        "status": "PASS",
        "method": "scalar rational leaf currents transported along literal forward T paths; no production import",
        "reviewed_sha256": PINNED,
        "flow_cases": records,
        "finite_continuation_tail_checks": finite_tail_checks,
        "antichain_roots": antichain,
        "counts": dict(sorted(COUNTS.items())),
        "negative_controls_rejected": rejected,
        "scope": "finite implementation corroboration; infinite statements were separately reconstructed in ANALYTIC_REVIEW.md",
        "limitations": ["Internal agent review, not external review or formal proof.",
                        "No Collatz proof and no novelty claim for signed eigenvectors in general."],
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--output", type=Path)
    group.add_argument("--compare", type=Path)
    args = parser.parse_args()
    report = run()
    rendered = json.dumps(report, indent=2, sort_keys=True) + "\n"
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        with args.output.open("x", encoding="utf-8") as handle:
            handle.write(rendered)
    elif args.compare:
        require(json.loads(args.compare.read_text()) == report, "frozen independent report differs")
    print(json.dumps({"status": "PASS", "flow_cases": len(report["flow_cases"]),
                      "counts": report["counts"],
                      "report_sha256": sha256(rendered.encode()).hexdigest()}, sort_keys=True))


if __name__ == "__main__":
    main()
